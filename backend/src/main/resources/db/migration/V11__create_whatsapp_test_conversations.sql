CREATE TABLE whatsapp_test_conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL REFERENCES businesses(id),
    customer_id BIGINT NOT NULL REFERENCES customers(id),
    state VARCHAR(32) NOT NULL,
    product_id BIGINT REFERENCES products(id),
    quantity NUMERIC(12, 3),
    quoted_unit_price NUMERIC(12, 2),
    order_id BIGINT REFERENCES orders(id),
    order_number VARCHAR(32),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_whatsapp_test_conversations_business
    ON whatsapp_test_conversations (business_id, id);

CREATE TABLE whatsapp_test_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL REFERENCES businesses(id),
    conversation_id BIGINT NOT NULL REFERENCES whatsapp_test_conversations(id),
    message_id VARCHAR(160) NOT NULL,
    reply_text VARCHAR(2000) NOT NULL,
    state VARCHAR(32) NOT NULL,
    order_id BIGINT REFERENCES orders(id),
    order_number VARCHAR(32),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_whatsapp_test_message_business UNIQUE (business_id, message_id)
);

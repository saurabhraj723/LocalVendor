CREATE TABLE whatsapp_test_cart_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES whatsapp_test_conversations(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products(id),
    quantity NUMERIC(12, 3) NOT NULL,
    quoted_unit_price NUMERIC(12, 2) NOT NULL,
    CONSTRAINT uq_whatsapp_test_cart_product UNIQUE (conversation_id, product_id)
);
